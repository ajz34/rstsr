/// Driver capability for strided batched GEMM (`?gemm_batch_strided`).
///
/// One parameter set for the whole batch; the `i`-th matrix of an operand is
/// at `base + i * stride` (strides in elements). `stride == 0` is legal and
/// reuses the same matrix for every batch element (the broadcast case).
///
/// This is a BLAS *extension* (e.g. OpenBLAS >= 0.3.34, MKL), not standard
/// BLAS, hence it is not bound to any standard driver trait.
pub trait BatchedGEMMStridedDriverAPI<T> {
    /// Strided batched GEMM.
    ///
    /// # Safety
    ///
    /// `a`, `b`, `c` must be valid for the shapes given by `m`, `n`, `k` and
    /// the leading dimensions, for `batch_count` matrices spaced by the
    /// respective strides, for the whole duration of the call.
    #[allow(clippy::too_many_arguments)]
    unsafe fn driver_batched_gemm_strided(
        order: FlagOrder,
        transa: FlagTrans,
        transb: FlagTrans,
        m: usize,
        n: usize,
        k: usize,
        alpha: T,
        a: *const T,
        lda: usize,
        stride_a: usize,
        b: *const T,
        ldb: usize,
        stride_b: usize,
        beta: T,
        c: *mut T,
        ldc: usize,
        stride_c: usize,
        batch_count: usize,
    ) -> Result<()>;
}
