/// Driver capability for grouped batched GEMM (`?gemm_batch`).
///
/// This wraps the pointer-array batched GEMM extension: each group carries its
/// own parameters, and `group_size[i]` consecutive pointer-array entries use
/// the parameters of group `i`. The uniform pointer-batch case is
/// `group_count == 1`, `group_size == [batch_count]`.
///
/// This is a BLAS *extension* (e.g. OpenBLAS >= 0.3.26, MKL), not standard
/// BLAS, hence it is not bound to any standard driver trait.
pub trait BatchedGEMMDriverAPI<T> {
    /// Grouped batched GEMM.
    ///
    /// All parameter slices must have length `group_count` except `a`/`b`/`c`
    /// (pointer arrays, total length `sum(group_size)`); strides and leading
    /// dimensions are in elements.
    ///
    /// # Safety
    ///
    /// All pointers in `a`, `b`, `c` must be valid for the shapes and leading
    /// dimensions given by the parameter arrays, for the whole duration of
    /// the call.
    #[allow(clippy::too_many_arguments)]
    unsafe fn driver_batched_gemm(
        order: FlagOrder,
        transa: &[FlagTrans],
        transb: &[FlagTrans],
        m: &[usize],
        n: &[usize],
        k: &[usize],
        alpha: &[T],
        a: &[*const T],
        lda: &[usize],
        b: &[*const T],
        ldb: &[usize],
        beta: &[T],
        c: &[*mut T],
        ldc: &[usize],
        group_count: usize,
        group_size: &[usize],
    ) -> Result<()>;
}
