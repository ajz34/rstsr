/// Grouped (pointer-based) batched GEMM over the `?gemm_batch` extension.
///
/// # Safety
///
/// All pointers in `a`, `b`, `c` must be valid for the shapes and leading
/// dimensions given by the parameter arrays, for the whole duration of the
/// call.
#[allow(clippy::too_many_arguments)]
pub unsafe fn fn_name(
    order: FlagOrder,
    transa: &[FlagTrans],
    transb: &[FlagTrans],
    m: &[usize],
    n: &[usize],
    k: &[usize],
    alpha: &[ty],
    a: &[*const ty],
    lda: &[usize],
    b: &[*const ty],
    ldb: &[usize],
    beta: &[ty],
    c: &[*mut ty],
    ldc: &[usize],
    group_count: usize,
    group_size: &[usize],
) -> Result<()> {
    rstsr_assert_eq!(transa.len(), group_count, InvalidLayout)?;
    rstsr_assert_eq!(transb.len(), group_count, InvalidLayout)?;
    rstsr_assert_eq!(m.len(), group_count, InvalidLayout)?;
    rstsr_assert_eq!(n.len(), group_count, InvalidLayout)?;
    rstsr_assert_eq!(k.len(), group_count, InvalidLayout)?;
    rstsr_assert_eq!(alpha.len(), group_count, InvalidLayout)?;
    rstsr_assert_eq!(lda.len(), group_count, InvalidLayout)?;
    rstsr_assert_eq!(ldb.len(), group_count, InvalidLayout)?;
    rstsr_assert_eq!(beta.len(), group_count, InvalidLayout)?;
    rstsr_assert_eq!(ldc.len(), group_count, InvalidLayout)?;
    rstsr_assert_eq!(group_size.len(), group_count, InvalidLayout)?;
    let total: usize = group_size.iter().sum();
    rstsr_assert_eq!(a.len(), total, InvalidLayout)?;
    rstsr_assert_eq!(b.len(), total, InvalidLayout)?;
    rstsr_assert_eq!(c.len(), total, InvalidLayout)?;

    let transa_arr: Vec<_> = transa.iter().map(|&t| cblas_trans_of(t)).collect::<Result<Vec<_>>>()?;
    let transb_arr: Vec<_> = transb.iter().map(|&t| cblas_trans_of(t)).collect::<Result<Vec<_>>>()?;
    let m_arr = int_vec(m)?;
    let n_arr = int_vec(n)?;
    let k_arr = int_vec(k)?;
    let lda_arr = int_vec(lda)?;
    let ldb_arr = int_vec(ldb)?;
    let ldc_arr = int_vec(ldc)?;
    let group_size_arr = int_vec(group_size)?;
    let group_count = as_blas_int(group_count)?;
    let mut a_arr: Vec<*const ty> = a.to_vec();
    let mut b_arr: Vec<*const ty> = b.to_vec();
    let mut c_arr: Vec<*mut ty> = c.to_vec();

    cblas_wrap(
        cblas_order_of(order),
        transa_arr.as_ptr(),
        transb_arr.as_ptr(),
        m_arr.as_ptr(),
        n_arr.as_ptr(),
        k_arr.as_ptr(),
        alpha.as_ptr(),
        a_arr.as_mut_ptr(),
        lda_arr.as_ptr(),
        b_arr.as_mut_ptr(),
        ldb_arr.as_ptr(),
        beta.as_ptr(),
        c_arr.as_mut_ptr(),
        ldc_arr.as_ptr(),
        group_count,
        group_size_arr.as_ptr(),
    );
    Ok(())
}

