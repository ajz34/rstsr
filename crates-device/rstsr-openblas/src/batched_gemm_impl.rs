    // naive reference for one row-major [m, k] @ [k, n] matrix
    fn naive_matmul(m: usize, n: usize, k: usize, a: &[f64], b: &[f64]) -> Vec<f64> {
        let mut c = vec![0.0; m * n];
        for i in 0..m {
            for j in 0..n {
                let mut acc = 0.0;
                for p in 0..k {
                    acc += a[i * k + p] * b[p * n + j];
                }
                c[i * n + j] = acc;
            }
        }
        c
    }

    // read a col-major [rows, cols] matrix slice into row-major order
    fn col_to_row(v: &[f64], rows: usize, cols: usize) -> Vec<f64> {
        (0..rows).flat_map(|r| (0..cols).map(move |c| v[c * rows + r])).collect()
    }

    #[cfg(feature = "use_batched_gemm")]
    #[test]
    fn test_batched_gemm_f64_grouped() {
        // batch of 3 matrices, m=2, k=3, n=4, col-major storage per matrix
        let (m, n, k, batch) = (2usize, 4usize, 3usize, 3usize);
        let a_data: Vec<f64> = linspace((0.0, 1.0, batch * m * k)).into_vec();
        let b_data: Vec<f64> = linspace((1.0, 2.0, batch * k * n)).into_vec();
        let mut c_data = vec![f64::ZERO; batch * m * n];

        let a_ptrs: Vec<*const f64> = (0..batch).map(|i| unsafe { a_data.as_ptr().add(i * m * k) }).collect();
        let b_ptrs: Vec<*const f64> = (0..batch).map(|i| unsafe { b_data.as_ptr().add(i * k * n) }).collect();
        let c_ptrs: Vec<*mut f64> =
            (0..batch).map(|i| unsafe { c_data.as_mut_ptr().add(i * m * n) }).collect();

        unsafe {
            batched_gemm_f64(
                ColMajor,
                &[FlagTrans::N],
                &[FlagTrans::N],
                &[m],
                &[n],
                &[k],
                &[1.0],
                &a_ptrs,
                &[m],
                &b_ptrs,
                &[k],
                &[0.0],
                &c_ptrs,
                &[m],
                1,
                &[batch],
            )
        }
        .unwrap();

        // two groups with identical parameters must give the same result
        let mut c2_data = vec![f64::ZERO; batch * m * n];
        let c2_ptrs: Vec<*mut f64> =
            (0..batch).map(|i| unsafe { c2_data.as_mut_ptr().add(i * m * n) }).collect();
        unsafe {
            batched_gemm_f64(
                ColMajor,
                &[FlagTrans::N, FlagTrans::N],
                &[FlagTrans::N, FlagTrans::N],
                &[m, m],
                &[n, n],
                &[k, k],
                &[1.0, 1.0],
                &a_ptrs,
                &[m, m],
                &b_ptrs,
                &[k, k],
                &[0.0, 0.0],
                &c2_ptrs,
                &[m, m],
                2,
                &[2, 1],
            )
        }
        .unwrap();
        assert_eq!(c_data, c2_data);

        // per-matrix reference
        for i in 0..batch {
            let a_rm = col_to_row(&a_data[i * m * k..(i + 1) * m * k], m, k);
            let b_rm = col_to_row(&b_data[i * k * n..(i + 1) * k * n], k, n);
            let expect = naive_matmul(m, n, k, &a_rm, &b_rm);
            let got = col_to_row(&c_data[i * m * n..(i + 1) * m * n], m, n);
            assert!(got.iter().zip(expect.iter()).all(|(x, y)| (x - y).abs() < 1e-10));
        }

        // alpha/beta accumulate
        let mut c3_data = vec![1.0; batch * m * n];
        let c3_ptrs: Vec<*mut f64> =
            (0..batch).map(|i| unsafe { c3_data.as_mut_ptr().add(i * m * n) }).collect();
        unsafe {
            batched_gemm_f64(
                ColMajor,
                &[FlagTrans::N],
                &[FlagTrans::N],
                &[m],
                &[n],
                &[k],
                &[2.0],
                &a_ptrs,
                &[m],
                &b_ptrs,
                &[k],
                &[3.0],
                &c3_ptrs,
                &[m],
                1,
                &[batch],
            )
        }
        .unwrap();
        for i in 0..batch {
            let a_rm = col_to_row(&a_data[i * m * k..(i + 1) * m * k], m, k);
            let b_rm = col_to_row(&b_data[i * k * n..(i + 1) * k * n], k, n);
            let expect = naive_matmul(m, n, k, &a_rm, &b_rm);
            for r in 0..m {
                for q in 0..n {
                    let got = c3_data[i * m * n + q * m + r];
                    let want = 2.0 * expect[r * n + q] + 3.0;
                    assert!((got - want).abs() < 1e-10);
                }
            }
        }
    }

