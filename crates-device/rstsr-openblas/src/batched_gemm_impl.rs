/// Layout pieces of one broadcasted matmul, eligible for batched GEMM.
pub(crate) struct BatchedMatmulPieces {
    pub lc_matmul: Layout<Ix2>,
    pub lc_rest: Layout<IxD>,
    pub la_matmul: Layout<Ix2>,
    pub la_rest: Layout<IxD>,
    pub lb_matmul: Layout<Ix2>,
    pub lb_rest: Layout<IxD>,
}

/// Layout-level eligibility check for batched GEMM acceleration.
///
/// Returns `None` (not an error) whenever the case should be handled by the
/// existing per-slice loop: non-batched rules, degenerate sizes, a batch of
/// one matrix, or a same-buffer product that the per-slice path can serve
/// with `syrk`.
pub(crate) fn batched_matmul_prepare<TA, TB, TC>(
    a: &[TA],
    la: &Layout<IxD>,
    b: &[TB],
    lb: &Layout<IxD>,
    lc: &Layout<IxD>,
    beta_is_zero: bool,
) -> Result<Option<BatchedMatmulPieces>>
where
    TA: 'static,
    TB: 'static,
    TC: 'static,
{
    if la.ndim() < 2 || lb.ndim() < 2 || lc.ndim() < 2 {
        return Ok(None);
    }
    if lc.size() == 0 {
        return Ok(None);
    }

    let cfg = layout_matmul_dyn_row_major_with_lc(la, lb, lc)?;
    match cfg.matmul_type {
        MatMulType::GEMM2X | MatMulType::GEMMX2 | MatMulType::GEMMXX => (),
        _ => return Ok(None),
    }

    let la_rest = cfg.la_rest.clone().unwrap();
    let lb_rest = cfg.lb_rest.clone().unwrap();
    let lc_rest = cfg.lc_rest.clone().unwrap();
    let count = lc_rest.size();

    // a batch of one matrix is better served by a plain gemm call
    if count <= 1 {
        return Ok(None);
    }
    // degenerate matrix sizes are handled by the fallback path
    if cfg.lc_matmul.shape()[0] == 0 || cfg.lc_matmul.shape()[1] == 0 || cfg.la_matmul.shape()[1] == 0 {
        return Ok(None);
    }

    // defer same-buffer products to the per-slice path, which can use syrk
    let lb_matmul_rev = cfg.lb_matmul.reverse_axes();
    if beta_is_zero
        && same_type::<TA, TB>()
        && same_type::<TA, TC>()
        && core::ptr::eq(a.as_ptr() as *const u8, b.as_ptr() as *const u8)
        && a.len() == b.len()
        && la_rest.shape() == lb_rest.shape()
        && la_rest.stride() == lb_rest.stride()
        && la_rest.offset() == lb_rest.offset()
        && cfg.la_matmul.shape() == lb_matmul_rev.shape()
        && cfg.la_matmul.stride() == lb_matmul_rev.stride()
    {
        return Ok(None);
    }

    Ok(Some(BatchedMatmulPieces {
        lc_matmul: cfg.lc_matmul.clone().into_dim::<Ix2>()?,
        lc_rest,
        la_matmul: cfg.la_matmul.clone().into_dim::<Ix2>()?,
        la_rest,
        lb_matmul: cfg.lb_matmul.clone().into_dim::<Ix2>()?,
        lb_rest,
    }))
}

/// Resolve which operand slice/rest plays the `A` role after a possible
/// `C^T = B^T A^T` swap.
fn roles_by_swap<'a, T>(
    swapped: bool,
    a: &'a [T],
    la_rest: &'a Layout<IxD>,
    b: &'a [T],
    lb_rest: &'a Layout<IxD>,
) -> (&'a [T], &'a Layout<IxD>, &'a [T], &'a Layout<IxD>) {
    if swapped {
        (b, lb_rest, a, la_rest)
    } else {
        (a, la_rest, b, lb_rest)
    }
}

/// Try to accelerate a broadcasted matmul with strided batched GEMM
/// (feature `use_batched_gemm_strided`).
///
/// Returns `Ok(true)` if the computation was performed, `Ok(false)` if the
/// case is not eligible and the caller should fall back (grouped batched
/// GEMM, or the existing per-slice loop).
#[cfg(feature = "use_batched_gemm_strided")]
#[allow(clippy::too_many_arguments)]
pub fn batched_matmul_strided_try<TA, TB, TC>(
    c: &mut [TC],
    lc: &Layout<IxD>,
    a: &[TA],
    la: &Layout<IxD>,
    b: &[TB],
    lb: &Layout<IxD>,
    alpha: TC,
    beta: TC,
    nthreads: usize,
) -> Result<bool>
where
    TA: Clone + Send + Sync + 'static,
    TB: Clone + Send + Sync + 'static,
    TC: Clone + Send + Sync + 'static,
    TA: Mul<TB, Output = TC>,
    TC: Mul<TC, Output = TC> + Add<TC, Output = TC> + Zero + PartialEq,
{
    let beta_is_zero = beta == TC::zero();
    let Some(pieces) = batched_matmul_prepare::<TA, TB, TC>(a, la, b, lb, lc, beta_is_zero)? else {
        return Ok(false);
    };

    macro_rules! impl_batched_dispatch {
        ($ty:ty) => {
            if same_type::<TA, $ty>() && same_type::<TB, $ty>() && same_type::<TC, $ty>() {
                let a2 = unsafe { core::slice::from_raw_parts(a.as_ptr() as *const $ty, a.len()) };
                let b2 = unsafe { core::slice::from_raw_parts(b.as_ptr() as *const $ty, b.len()) };
                let c2 = unsafe { core::slice::from_raw_parts_mut(c.as_mut_ptr() as *mut $ty, c.len()) };
                let alpha2 = unsafe { *(&alpha as *const TC as *const $ty) };
                let beta2 = unsafe { *(&beta as *const TC as *const $ty) };
                return batched_strided_core(&pieces, a2, b2, c2, alpha2, beta2, nthreads);
            }
        };
    }
    impl_batched_dispatch!(f32);
    impl_batched_dispatch!(f64);
    impl_batched_dispatch!(c32);
    impl_batched_dispatch!(c64);
    Ok(false)
}

#[cfg(feature = "use_batched_gemm_strided")]
#[allow(clippy::too_many_arguments)]
fn batched_strided_core<T>(
    pieces: &BatchedMatmulPieces,
    a: &[T],
    b: &[T],
    c: &mut [T],
    alpha: T,
    beta: T,
    nthreads: usize,
) -> Result<bool>
where
    T: 'static,
    crate::DeviceBLAS: BatchedGEMMStridedDriverAPI<T>,
{
    use crate::DeviceBLAS;

    let count = pieces.lc_rest.size();
    let Some((transa, la_m, transb, lb_m, lc_m, swapped)) =
        batched_canon_matmul(&pieces.la_matmul, &pieces.lb_matmul, &pieces.lc_matmul)
    else {
        return Ok(false);
    };
    let (a_slice, a_rest, b_slice, b_rest) = roles_by_swap(swapped, a, &pieces.la_rest, b, &pieces.lb_rest);

    // strided interface: every operand batch must be uniformly-strided, and
    // operands with nonzero stride must share the same flat order
    let (oa, sa) = match batched_flat_stride(a_rest) {
        Some(v) => v,
        None => return Ok(false),
    };
    let (ob, sb) = match batched_flat_stride(b_rest) {
        Some(v) => v,
        None => return Ok(false),
    };
    let (oc, sc) = match batched_flat_stride(&pieces.lc_rest) {
        Some(v) => v,
        None => return Ok(false),
    };
    let mut order: Option<BatchedFlatOrder> = None;
    let mut consistent = true;
    for (o, s) in [(oa, sa), (ob, sb), (oc, sc)] {
        if s > 0 {
            match order {
                None => order = Some(o),
                Some(prev) if prev == o => (),
                _ => consistent = false,
            }
        }
    }
    if !consistent {
        return Ok(false);
    }

    let (m, n, k) = batched_dims(transa, &la_m, &lc_m);
    let lda = batched_ld(&la_m);
    let ldb = batched_ld(&lb_m);
    let ldc = batched_ld(&lc_m);

    let ptr_a = unsafe { a_slice.as_ptr().add(a_rest.offset()) };
    let ptr_b = unsafe { b_slice.as_ptr().add(b_rest.offset()) };
    let ptr_c = unsafe { c.as_mut_ptr().add(pieces.lc_rest.offset()) };

    with_num_threads(nthreads, || -> Result<()> {
        unsafe {
            <DeviceBLAS as BatchedGEMMStridedDriverAPI<T>>::driver_batched_gemm_strided(
                ColMajor, transa, transb, m, n, k, alpha, ptr_a, lda, sa, ptr_b, ldb, sb, beta, ptr_c, ldc, sc,
                count,
            )
        }
    })?;
    Ok(true)
}

/// Try to accelerate a broadcasted matmul with grouped (pointer-based)
/// batched GEMM (feature `use_batched_gemm`), gathering one pointer per
/// matrix. Handles scattered batch layouts of any operand.
///
/// Returns `Ok(true)` if the computation was performed, `Ok(false)` if the
/// case is not eligible and the caller should fall back to the existing
/// per-slice loop.
#[cfg(feature = "use_batched_gemm")]
#[allow(clippy::too_many_arguments)]
pub fn batched_matmul_grouped_try<TA, TB, TC>(
    c: &mut [TC],
    lc: &Layout<IxD>,
    a: &[TA],
    la: &Layout<IxD>,
    b: &[TB],
    lb: &Layout<IxD>,
    alpha: TC,
    beta: TC,
    nthreads: usize,
) -> Result<bool>
where
    TA: Clone + Send + Sync + 'static,
    TB: Clone + Send + Sync + 'static,
    TC: Clone + Send + Sync + 'static,
    TA: Mul<TB, Output = TC>,
    TC: Mul<TC, Output = TC> + Add<TC, Output = TC> + Zero + PartialEq,
{
    let beta_is_zero = beta == TC::zero();
    let Some(pieces) = batched_matmul_prepare::<TA, TB, TC>(a, la, b, lb, lc, beta_is_zero)? else {
        return Ok(false);
    };

    macro_rules! impl_batched_dispatch {
        ($ty:ty) => {
            if same_type::<TA, $ty>() && same_type::<TB, $ty>() && same_type::<TC, $ty>() {
                let a2 = unsafe { core::slice::from_raw_parts(a.as_ptr() as *const $ty, a.len()) };
                let b2 = unsafe { core::slice::from_raw_parts(b.as_ptr() as *const $ty, b.len()) };
                let c2 = unsafe { core::slice::from_raw_parts_mut(c.as_mut_ptr() as *mut $ty, c.len()) };
                let alpha2 = unsafe { *(&alpha as *const TC as *const $ty) };
                let beta2 = unsafe { *(&beta as *const TC as *const $ty) };
                return batched_grouped_core(&pieces, a2, b2, c2, alpha2, beta2, nthreads);
            }
        };
    }
    impl_batched_dispatch!(f32);
    impl_batched_dispatch!(f64);
    impl_batched_dispatch!(c32);
    impl_batched_dispatch!(c64);
    Ok(false)
}

#[cfg(feature = "use_batched_gemm")]
#[allow(clippy::too_many_arguments)]
fn batched_grouped_core<T>(
    pieces: &BatchedMatmulPieces,
    a: &[T],
    b: &[T],
    c: &mut [T],
    alpha: T,
    beta: T,
    nthreads: usize,
) -> Result<bool>
where
    T: 'static,
    crate::DeviceBLAS: BatchedGEMMDriverAPI<T>,
{
    use crate::DeviceBLAS;

    let count = pieces.lc_rest.size();
    let Some((transa, la_m, transb, lb_m, lc_m, swapped)) =
        batched_canon_matmul(&pieces.la_matmul, &pieces.lb_matmul, &pieces.lc_matmul)
    else {
        return Ok(false);
    };
    let (a_slice, a_rest, b_slice, b_rest) = roles_by_swap(swapped, a, &pieces.la_rest, b, &pieces.lb_rest);

    let (m, n, k) = batched_dims(transa, &la_m, &lc_m);
    let lda = batched_ld(&la_m);
    let ldb = batched_ld(&lb_m);
    let ldc = batched_ld(&lc_m);

    // gather one pointer per matrix; any batch layout is accepted here
    let ita = IterLayoutColMajor::new(a_rest)?;
    let itb = IterLayoutColMajor::new(b_rest)?;
    let itc = IterLayoutColMajor::new(&pieces.lc_rest)?;
    let mut a_ptrs: Vec<*const T> = Vec::with_capacity(count);
    let mut b_ptrs: Vec<*const T> = Vec::with_capacity(count);
    let mut c_ptrs: Vec<*mut T> = Vec::with_capacity(count);
    for (ia, ib, ic) in izip!(ita, itb, itc) {
        a_ptrs.push(unsafe { a_slice.as_ptr().add(ia) });
        b_ptrs.push(unsafe { b_slice.as_ptr().add(ib) });
        c_ptrs.push(unsafe { c.as_mut_ptr().add(ic) });
    }

    with_num_threads(nthreads, || -> Result<()> {
        unsafe {
            <DeviceBLAS as BatchedGEMMDriverAPI<T>>::driver_batched_gemm(
                ColMajor,
                &[transa],
                &[transb],
                &[m],
                &[n],
                &[k],
                &[alpha],
                &a_ptrs,
                &[lda],
                &b_ptrs,
                &[ldb],
                &[beta],
                &c_ptrs,
                &[ldc],
                1,
                &[count],
            )
        }
    })?;
    Ok(true)
}

