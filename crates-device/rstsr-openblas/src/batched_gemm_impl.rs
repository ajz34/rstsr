/*!
Batched GEMM extensions for the OpenBLAS device.

Two OpenBLAS extension interfaces are wrapped here:

- grouped (pointer-based) `?gemm_batch`, behind feature `use_batched_gemm`;
- strided `?gemm_batch_strided`, behind feature `use_batched_gemm_strided`.

The functions in this module are for internal usage: they are public, but
*not* intended as user API. They are `unsafe` and take raw pointers; the
user-facing entry points are `rt::linalg::batched_matmul` /
`rt::linalg::batched_matmul_strided`, and the broadcasted `rt::matmul` which
dispatches onto them (see [`batched_matmul_strided_try`] and
[`batched_matmul_grouped_try`]).

Most or all contents generated by AI (model glm-5.3).
*/

