            let c_ptrs: Vec<*mut f64> =
                (0..batch).map(|i| unsafe { c_ref.as_mut_ptr().add(i * m * n) }).collect();
            unsafe {
                batched_gemm_f64(
                    ColMajor, &[FlagTrans::N], &[FlagTrans::N], &[m], &[n], &[k], &[1.0], &a_ptrs, &[m],
                    &b_ptrs, &[k], &[0.0], &c_ptrs, &[m], 1, &[batch],
                )
            }
            .unwrap();
