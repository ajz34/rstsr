    #[cfg(feature = "use_batched_gemm")]
    #[test]
    fn test_batched_matmul_grouped_try_scattered() {
        // rank-4 batched matmul with a scattered A batch (strided slice of an
        // outer batch dim): rest strides [24, 6] cannot flatten to one stride
        let (m, n, k) = (2usize, 4usize, 3usize);
        let (b0, b1) = (2usize, 2usize);
        let batch = b0 * b1;
        let a_data: Vec<f64> = linspace((0.0, 1.0, 200)).into_vec();
        let b_data: Vec<f64> = linspace((1.0, 2.0, batch * k * n)).into_vec();
        let mut c_data = vec![f64::ZERO; batch * m * n];

        // A: shape [2, 2, 2, 3], strides [24, 6, 3, 1] (scattered on dim 0)
        let la = Layout::new(vec![b0, b1, m, k], vec![24, 6, 3, 1], 0).unwrap();
        let lb = [b0, b1, k, n].c().to_dim::<IxD>().unwrap();
        let lc = [b0, b1, m, n].c().to_dim::<IxD>().unwrap();
        let handled =
            batched_matmul_grouped_try(&mut c_data, &lc, &a_data, &la, &b_data, &lb, 1.0, 0.0, 1).unwrap();
        assert!(handled);

        let mut idx = 0;
        for i0 in 0..b0 {
            for i1 in 0..b1 {
                let base_a = i0 * 24 + i1 * 6;
                let a_rm = &a_data[base_a..base_a + m * k];
                let base_b = (i0 * b1 + i1) * k * n;
                let b_rm = &b_data[base_b..base_b + k * n];
                let expect = naive_matmul(m, n, k, a_rm, b_rm);
                let base_c = idx * m * n;
                let got = &c_data[base_c..base_c + m * n];
                assert!(got.iter().zip(expect.iter()).all(|(x, y)| (x - y).abs() < 1e-10));
                idx += 1;
            }
        }
        assert_eq!(idx, batch);
    }

    #[cfg(all(feature = "use_batched_gemm", feature = "use_batched_gemm_strided"))]
    #[test]
    fn test_batched_gemm_c32_grouped() {
        let (m, n, k, batch) = (2usize, 3usize, 3usize, 2usize);
        let a_data: Vec<c32> = linspace((c32::new(1., 1.), c32::new(6., 6.), batch * m * k)).into_vec();
        let b_data: Vec<c32> = linspace((c32::new(1., -1.), c32::new(9., -9.), batch * k * n)).into_vec();
        let mut c_data = vec![c32::ZERO; batch * m * n];

        let a_ptrs: Vec<*const c32> = (0..batch).map(|i| unsafe { a_data.as_ptr().add(i * m * k) }).collect();
        let b_ptrs: Vec<*const c32> = (0..batch).map(|i| unsafe { b_data.as_ptr().add(i * k * n) }).collect();
        let c_ptrs: Vec<*mut c32> =
            (0..batch).map(|i| unsafe { c_data.as_mut_ptr().add(i * m * n) }).collect();

        unsafe {
            batched_gemm_c32(
                ColMajor,
                &[FlagTrans::N],
                &[FlagTrans::N],
                &[m],
                &[n],
                &[k],
                &[c32::ONE],
                &a_ptrs,
                &[m],
                &b_ptrs,
                &[k],
                &[c32::ZERO],
                &c_ptrs,
                &[m],
                1,
                &[batch],
            )
        }
        .unwrap();

        // cross-check with per-matrix gemm (col-major layouts, matching the
        // col-major packing above)
        for i in 0..batch {
            let la = [m, k].f();
            let lb = [k, n].f();
            let lc = [m, n].f();
            let mut c_ref = vec![c32::ZERO; m * n];
            let pool = None;
            crate::matmul_impl::gemm_blas_no_conj_c32(
                &mut c_ref,
                &lc,
                &a_data[i * m * k..(i + 1) * m * k],
                &la,
                &b_data[i * k * n..(i + 1) * k * n],
                &lb,
                c32::ONE,
                c32::ZERO,
                pool,
            )
            .unwrap();
            // different kernels round differently in f32: compare with tolerance
            let got = &c_data[i * m * n..(i + 1) * m * n];
            assert!(got.iter().zip(c_ref.iter()).all(|(x, y)| {
                (x.re - y.re).abs() < 1e-4 * (1.0 + y.re.abs()) && (x.im - y.im).abs() < 1e-4
            }));
        }
    }
