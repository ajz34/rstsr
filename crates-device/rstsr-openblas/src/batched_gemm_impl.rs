/* #region helpers */

fn same_type<A: 'static, B: 'static>() -> bool {
    TypeId::of::<A>() == TypeId::of::<B>()
}

fn cblas_order_of(order: FlagOrder) -> cblas::CBLAS_LAYOUT {
    match order {
        RowMajor => cblas::CBLAS_LAYOUT::CblasRowMajor,
        ColMajor => cblas::CBLAS_LAYOUT::CblasColMajor,
    }
}

fn cblas_trans_of(t: FlagTrans) -> Result<cblas::CBLAS_TRANSPOSE> {
    match t {
        FlagTrans::N => Ok(cblas::CBLAS_TRANSPOSE::CblasNoTrans),
        FlagTrans::T => Ok(cblas::CBLAS_TRANSPOSE::CblasTrans),
        FlagTrans::C => Ok(cblas::CBLAS_TRANSPOSE::CblasConjTrans),
        // conjugate-only (no transpose) has no cblas equivalent in this
        // OpenBLAS build; callers needing it should clone and conjugate the
        // data explicitly
        _ => rstsr_invalid!(t)?,
    }
}

fn as_blas_int(v: usize) -> Result<cblas::blas_int> {
    rstsr_assert!(v <= cblas::blas_int::MAX as usize, Miscellaneous)?;
    Ok(v as cblas::blas_int)
}

fn int_vec(v: &[usize]) -> Result<Vec<cblas::blas_int>> {
    v.iter().map(|&x| as_blas_int(x)).collect()
}

